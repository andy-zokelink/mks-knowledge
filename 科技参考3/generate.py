# ============================================================
# CATEGORIZE
# ============================================================
def categorize(article):
    title = article['title']
    best_topic = None
    best_score = 0

    for tname, tdata in TOPICS.items():
        score = 0
        for kw in tdata['keywords']:
            if kw.lower() in title.lower():
                score += 1
        if score > best_score:
            best_score = score
            best_topic = tname

    # fallback: read content to guess
    if best_score == 0:
        content = (article.get('content') or '')[:500]
        for tname, tdata in TOPICS.items():
            score = 0
            for kw in tdata['keywords'][:20]:  # top keywords only
                if kw.lower() in content.lower():
                    score += 0.5
            if score > best_score:
                best_score = score
                best_topic = tname

    if best_score == 0:
        best_topic = "7-科学方法与认知论"  # Everything goes somewhere

    return best_topic

# Assign categories
